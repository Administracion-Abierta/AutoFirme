#!/usr/bin/env bash
# Refreshes the bundled FNMT trust anchor (AGENTS.md: fetch latest from fnmt.es, commit only the PEM).
set -euo pipefail

dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="$dir/src/lib/verify/roots/fnmt-racm.ts"
url="http://www.cert.fnmt.es/certs/ACRAIZFNMT.crt"
# AC RAIZ FNMT-RCM, as published in the Mozilla root store.
expected="EB:C5:57:0C:29:01:8C:4D:67:B1:AA:12:7B:AF:12:F7:03:B4:61:1E:BC:17:B7:DA:B5:57:38:94:17:9B:93:FA"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

curl -sSL -o "$tmp/root.crt" "$url"
openssl x509 -in "$tmp/root.crt" -inform DER -out "$tmp/root.pem"

subject="$(openssl x509 -in "$tmp/root.pem" -noout -subject)"
fingerprint="$(openssl x509 -in "$tmp/root.pem" -noout -fingerprint -sha256 | cut -d= -f2)"
[[ "$subject" == *"AC RAIZ FNMT-RCM"* ]] || { echo "unexpected subject: $subject" >&2; exit 1; }
[[ "$fingerprint" == "$expected" ]] || { echo "fingerprint drift: $fingerprint (expected $expected)" >&2; exit 1; }

{
  echo "/**"
  echo " * Bundled FNMT trust anchor, generated by \`scripts/fetch-roots.sh\` (never edited by hand):"
  echo " * AC RAIZ FNMT-RCM, sha256=$fingerprint."
  echo " * refreshed $(date -u +%Y-%m-%dT%H:%M:%SZ) for the TSL/LOTL bundle (Refs #135)."
  echo " */"
  echo "export const FNMT_RACM_PEM = \`$(cat "$tmp/root.pem")"
  echo "\`;"
} > "$target"
echo "ok $target  $subject  sha256=$fingerprint"
echo "fetched $(date -u +%Y-%m-%dT%H:%M:%SZ) from $url — paste into TRUST_BUNDLE_META.fetchedAt on review (Refs #135)"
